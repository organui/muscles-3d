function noteFor({ parts }: Source) {
  const paired = parts.some((p) => /\b(left|right)\b/.test(p))
  const sides = paired ? 'Left and right sides are drawn and selected together. ' : ''
  return `${sides}Source meshes: ${parts.join('; ')}. Shapes are simplified for the web; colors are illustrative.`
}

